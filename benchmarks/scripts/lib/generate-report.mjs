import { formatJankEvidence } from './parse-gfxinfo.mjs'

const RELEASE_PROFILER_NOTE =
  'N/A — React Profiler is disabled for the release-frame claim (`enableProfiling` is off in release)'

const AUTOMATION_BLANKING_NOTE =
  'not classified by automation; see the screenshot next to the gfxinfo dump if attached'

export function generateReportMarkdown(session) {
  const deviceRows = session.devices
    .map(
      (device) =>
        `| ${md(device.label)} | ${md(device.os)} | ${md(device.storageThermal)} | \`adb dumpsys gfxinfo\` |`
    )
    .join('\n')

  const resultRows = session.runs
    .map((run) => {
      const artifact = run.rawArtifact ? `[capture](${run.rawArtifact})` : 'missing'
      const jank = run.error ? `FAILED: ${run.error}` : formatJankEvidence(run.metrics)
      return [
        '',
        md(run.deviceLabel),
        md(run.dataset),
        md(run.renderer),
        md(run.implementation),
        md(run.scenario),
        String(run.repetition),
        md(jank),
        md(RELEASE_PROFILER_NOTE),
        md(formatMemory(run.memoryPssKb)),
        md(AUTOMATION_BLANKING_NOTE),
        artifact
      ].join(' | ')
    })
    .join('\n')

  return `# Release-build benchmark report

> Generated by \`pnpm benchmark:android:run\`. This file is publishable evidence only together with
> the linked raw captures from the same session.

## Build identity

| Field                             | Value                                    |
| --------------------------------- | ---------------------------------------- |
| Source commit                     | \`${md(session.sourceCommit)}\` |
| Source tree dirty                 | ${session.sourceDirty ? 'yes' : 'no'} |
| Package version                   | \`${md(session.packageVersion)}\` |
| Build type                        | Android release |
| Build command/tool version        | ${md(session.buildCommand)} |
| React Native / Expo               | ${md(session.runtimeVersions)} |
| Profiling enabled for frame claim | No |
| Gesture driver                    | \`adb shell input swipe\` (physical device) |
| Frame diagnostic                  | raw \`dumpsys gfxinfo\` |
| Matrix                            | \`${md(session.matrixName)}\` |
| Generated at (UTC)                | ${md(session.generatedAtUtc)} |

## Physical devices

| Device                    | OS                  | Storage / thermal state | Frame diagnostic tool                           |
| ------------------------- | ------------------- | ----------------------- | ----------------------------------------------- |
${deviceRows}

## Method

- Cold-launch before each of ${session.repetitions} repetitions via \`rndg://lab\` (no operator taps).
- Use row overscan \`3\`, column overscan \`2\`, one left and one right pinned column.
- Compare only \`2D virtualized\` and \`Rows only\` with identical dataset, renderer, viewport, and
  gesture.
- Automated scenarios: fast vertical fling and fast horizontal fling. gfxinfo is reset after the lab
  is ready and dumped after the fling settles (${session.settleMs} ms). Idle frames after settle may
  be included in the totals.
- Visual blanking/pop-in is not classified by this runner.

## Results

One row per repetition.

| Device     | Dataset     | Renderer     | Implementation     | Scenario     | Run | Janky/dropped frame evidence | JS responsiveness / commits / mounts | Memory            | Blanking/pop-in     | Raw artifact              |
| ---------- | ----------- | ------------ | ------------------ | ------------ | --: | ---------------------------- | ------------------------------------ | ----------------- | ------------------- | ------------------------- |
${resultRows}

## Interpretation

${buildInterpretation(session)}
`
}

export function buildInterpretation(session) {
  const lines = [
    'Observations from this device session only. No external-library comparison was run.',
    'React commit and mount counters were not collected; this report is a release-frame diagnostic.',
    ''
  ]

  const groups = new Map()
  for (const run of session.runs) {
    if (!run.metrics || run.metrics.jankyPercent == null) continue
    const key = `${run.dataset} / ${run.renderer} / ${run.scenario}`
    const group = groups.get(key) ?? { twoDimensional: [], rowsOnly: [] }
    if (run.implementation === 'two-dimensional')
      group.twoDimensional.push(run.metrics.jankyPercent)
    if (run.implementation === 'rows-only') group.rowsOnly.push(run.metrics.jankyPercent)
    groups.set(key, group)
  }

  if (groups.size === 0) {
    lines.push(
      'No janky-frame percentages were parsed from gfxinfo, so 2D vs rows-only cannot be summarized.'
    )
    return lines.join('\n')
  }

  for (const [key, group] of groups) {
    lines.push(`### ${key}`)
    const twoD = summarizePercents(group.twoDimensional)
    const rows = summarizePercents(group.rowsOnly)
    lines.push(
      `- 2D virtualized: ${twoD == null ? 'no parsed runs' : `mean janky ${fmt(twoD.mean)}% (runs ${twoD.runs})`}`
    )
    lines.push(
      `- Rows only: ${rows == null ? 'no parsed runs' : `mean janky ${fmt(rows.mean)}% (runs ${rows.runs})`}`
    )
    if (twoD && rows) {
      const delta = rows.mean - twoD.mean
      const sign = delta > 0 ? '+' : ''
      lines.push(
        `- Rows-only − 2D mean janky-frame percent: ${sign}${fmt(delta)} percentage points (positive means rows-only had more jank).`
      )
    }
    lines.push('')
  }

  return lines.join('\n').trimEnd()
}

function summarizePercents(values) {
  if (values.length === 0) return null
  const mean = values.reduce((sum, value) => sum + value, 0) / values.length
  return {
    mean,
    runs: values.map((value) => fmt(value)).join(', ')
  }
}

function formatMemory(pssKb) {
  return pssKb == null ? 'N/A' : `TOTAL PSS ${pssKb} KB`
}

function fmt(value) {
  return Number(value.toFixed(2)).toString()
}

function md(value) {
  return String(value ?? '')
    .replaceAll('|', '\\|')
    .replaceAll('\n', ' ')
}
